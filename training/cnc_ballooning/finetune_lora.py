"""QLoRA Fine-Tuning Script for CNC Technical Drawing Ballooning (Qwen2.5-VL / Qwen3.5-VL).

Run this on a GPU machine (RTX 4060 8GB+ or cloud A100/L4) once you have collected real
company CNC drawings alongside the synthetic dataset generated by `generate_synthetic_dataset.py`.

Dependencies (install in a dedicated GPU training venv):
    pip install unsloth datasets trl peft bitsandbytes pillow

Usage:
    python training/cnc_ballooning/finetune_lora.py --dataset training/cnc_ballooning/data/dataset.jsonl
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description="Fine-tune a Vision-LLM with QLoRA for CNC Ballooning")
    parser.add_argument("--model", default="unsloth/Qwen2.5-VL-7B-Instruct-bnb-4bit")
    parser.add_argument("--dataset", type=Path, default=Path("training/cnc_ballooning/data/dataset.jsonl"))
    parser.add_argument("--output", type=Path, default=Path("training/cnc_ballooning/lora_adapter"))
    parser.add_argument("--epochs", type=int, default=3)
    parser.add_argument("--lr", type=float, default=2e-4)
    args = parser.parse_args()

    try:
        from PIL import Image
        from trl import SFTConfig, SFTTrainer
        from unsloth import FastVisionModel
        from unsloth.trainer import UnslothVisionDataCollator
    except ImportError as exc:
        raise SystemExit(
            f"Missing GPU training package ({exc}). Install with:\n"
            "  pip install unsloth trl peft bitsandbytes datasets pillow"
        ) from exc

    records = [json.loads(line) for line in args.dataset.read_text(encoding="utf-8").splitlines() if line.strip()]
    converted = []
    for rec in records:
        img = Image.open(rec["image"]).convert("RGB")
        converted.append({
            "messages": [
                {
                    "role": "user",
                    "content": [
                        {"type": "image", "image": img},
                        {"type": "text", "text": rec["messages"][0]["content"]},
                    ],
                },
                {
                    "role": "assistant",
                    "content": [{"type": "text", "text": rec["messages"][1]["content"]}],
                },
            ]
        })

    model, tokenizer = FastVisionModel.from_pretrained(args.model, load_in_4bit=True)
    model = FastVisionModel.get_peft_model(
        model,
        finetune_vision_layers=True,
        finetune_language_layers=True,
        finetune_attention_modules=True,
        finetune_mlp_modules=True,
        r=16,
        lora_alpha=16,
        lora_dropout=0.05,
        bias="none",
        random_state=42,
    )

    FastVisionModel.for_training(model)
    trainer = SFTTrainer(
        model=model,
        tokenizer=tokenizer,
        data_collator=UnslothVisionDataCollator(model, tokenizer),
        train_dataset=converted,
        args=SFTConfig(
            per_device_train_batch_size=1,
            gradient_accumulation_steps=4,
            warmup_steps=5,
            num_train_epochs=args.epochs,
            learning_rate=args.lr,
            logging_steps=1,
            optim="adamw_8bit",
            output_dir=str(args.output),
            remove_unused_columns=False,
            dataset_text_field="",
            dataset_kwargs={"skip_prepare_dataset": True},
        ),
    )
    trainer.train()
    model.save_pretrained(str(args.output))
    tokenizer.save_pretrained(str(args.output))
    print(f"LoRA adapter saved to {args.output}. Export to GGUF and load into Ollama with `ollama create`.")


if __name__ == "__main__":
    main()
